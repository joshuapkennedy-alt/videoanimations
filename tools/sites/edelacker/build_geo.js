// Writes src/cards/edelacker_geo.js: the Edelacker Einzellage parcels (traced from the outline screenshot) and the two
// VDP.Große Lage parcels, in the video's pixel space (1920x1080, frames after the camera settles at ~5 s).
//  - Große Lage 1 = the top of the small outlined block by the warehouses (the map shows the rest of it as non-Große Lage).
//  - Große Lage 2 = the slanted strip from the vineyard map, placed by anchoring the map to the big outlined field
//    above it (map px -> video px: x*1.414 - 132, y*1.414 + 11.8); it sits inside the outlined eastern lump.
const fs = require('fs');
const lage = JSON.parse(fs.readFileSync('ea/parcels.json'));
const bbox = P => P.reduce((b, [x, y]) => [Math.min(b[0], x), Math.min(b[1], y), Math.max(b[2], x), Math.max(b[3], y)], [1e9, 1e9, -1e9, -1e9]);
const small = lage.find(P => { const b = bbox(P); return b[0] < 862 && b[2] > 862 && b[1] < 170 && b[3] > 170 && b[2] - b[0] < 60; });
if (!small) throw new Error('small block not found');
// clip to y < 181 (Sutherland-Hodgman against one horizontal line)
function clipY(P, yc) { const out = []; for (let i = 0; i < P.length; i++) { const a = P[i], b = P[(i + 1) % P.length], ai = a[1] < yc, bi = b[1] < yc;
  if (ai) out.push(a); if (ai !== bi) { const t = (yc - a[1]) / (b[1] - a[1]); out.push([a[0] + t * (b[0] - a[0]), yc]); } } return out; }
const gl1 = clipY(small, 181);
const S1 = [[592.5, 155], [611, 154], [614, 164], [623, 187], [630, 196], [634, 219], [615.5, 220], [611, 196], [600, 173]];
const gl2 = S1.map(([x, y]) => [x * 1.414 - 132, y * 1.414 + 11.8]);
const d = P => 'M' + P.map(p => p.map(v => v.toFixed(1)).join(',')).join('L') + 'Z';
fs.writeFileSync('src/cards/edelacker_geo.js', '// Generated by the Edelacker tracing scripts: parcels in video pixels (1920x1080)\r\nwindow.EDEL = ' +
  JSON.stringify({ lage: lage.map(d), gl: [gl1, gl2].map(d) }) + ';\r\n');
console.log('lage', lage.length, 'gl1 bbox', bbox(gl1).map(Math.round), 'gl2 bbox', bbox(gl2).map(Math.round));
