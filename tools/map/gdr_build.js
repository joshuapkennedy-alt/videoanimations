// Builds cards/gdr_geo.js from a German states GeoJSON (isellsoap/deutschlandGeoJSON, 2_bundeslaender/3_mittel.geo.json):
//   border: the inner-German border, north to south = points of the eastern states lying on a western state's edge
//   east:   the five eastern states + Berlin as separate polygons (drawn as one opaque group, so seams don't show)
// in the map image's pixel space (same fitted equirectangular projection as paths.js).
const fs = require('fs');
const [src, fitf, out] = process.argv.slice(2);
const fit = JSON.parse(fs.readFileSync(fitf)).equirect, [sx, sy] = fit.s, [tx, ty] = fit.t, K = 1000 * Math.PI / 180;
const P = ([lon, lat]) => [sx * K * lon + tx, -sy * K * lat + ty];
const g = JSON.parse(fs.readFileSync(src));
const EAST = ['DE-MV', 'DE-BB', 'DE-BE', 'DE-ST', 'DE-TH', 'DE-SN'], WEST = new Set(['DE-SH', 'DE-NI', 'DE-HE', 'DE-BY']);
const rings = f => (f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates).map(p => p[0]);
// western edges in a 0.05 degree grid
const grid = new Map(), C = 0.05, gk = (x, y) => Math.floor(x / C) + ',' + Math.floor(y / C);
g.features.filter(f => WEST.has(f.properties.id)).forEach(f => rings(f).forEach(r => { for (let i = 0; i + 1 < r.length; i++) {
  const [a, b] = [r[i], r[i + 1]]; for (const [x, y] of [a, b]) { const k = gk(x, y); if (!grid.has(k)) grid.set(k, []); grid.get(k).push([a, b]); } } }));
function dist(p, [a, b]) { const cs = Math.cos(p[1] * Math.PI / 180), ax = a[0] * cs, bx = b[0] * cs, px = p[0] * cs;
  const dx = bx - ax, dy = b[1] - a[1], L = dx * dx + dy * dy, t = L ? Math.max(0, Math.min(1, ((px - ax) * dx + (p[1] - a[1]) * dy) / L)) : 0;
  return Math.hypot(px - ax - t * dx, p[1] - a[1] - t * dy); }
const TOL = 0.003;   // degrees, about 300 m
function onWest(p) { const cx = Math.floor(p[0] / C), cy = Math.floor(p[1] / C);
  for (let i = -1; i <= 1; i++) for (let j = -1; j <= 1; j++) for (const s of grid.get((cx + i) + ',' + (cy + j)) || []) if (dist(p, s) < TOL) return true; return false; }
let runs = [];
g.features.filter(f => EAST.includes(f.properties.id) && f.properties.id !== 'DE-BE').forEach(f => rings(f).forEach(r => {
  const ring = r.slice(0, -1), on = ring.map(onWest), n = ring.length; if (!on.some(Boolean)) return;
  let s = on.findIndex(v => !v); if (s < 0) return;
  let cur = null; for (let k = 1; k <= n; k++) { const i = (s + k) % n; if (on[i]) { (cur = cur || []).push(ring[i]); } else if (cur) { runs.push(cur); cur = null; } }
  if (cur) runs.push(cur);
}));
runs = runs.filter(r => r.length >= 2);
// join runs into one north-to-south line: orient each run north->south, then greedily chain from the northernmost
runs.forEach(r => { if (r[0][1] < r[r.length - 1][1]) r.reverse(); });
const len = r => r.reduce((s, p, i) => i ? s + Math.hypot(p[0] - r[i - 1][0], p[1] - r[i - 1][1]) : 0, 0);
runs = runs.filter(r => len(r) > 0.02);
runs.sort((a, b) => b[0][1] - a[0][1]);
const line = runs.shift().slice();
while (runs.length) { const e = line[line.length - 1]; let bi = 0, bd = 1e9, rev = false;
  runs.forEach((r, i) => { const d0 = Math.hypot(r[0][0] - e[0], r[0][1] - e[1]), d1 = Math.hypot(r[r.length - 1][0] - e[0], r[r.length - 1][1] - e[1]);
    if (d0 < bd) { bd = d0; bi = i; rev = false; } if (d1 < bd) { bd = d1; bi = i; rev = true; } });
  const r = runs.splice(bi, 1)[0]; if (bd > 0.15) console.log('gap', bd.toFixed(3), 'deg at', e.map(v => v.toFixed(2)).join(','));
  line.push(...(rev ? r.reverse() : r)); }
console.log('border points', line.length, 'from', line[0].map(v => v.toFixed(2)).join(','), 'to', line[line.length - 1].map(v => v.toFixed(2)).join(','));
const pd = pts => 'M' + pts.map(p => P(p).map(v => v.toFixed(1)).join(',')).join('L');
const east = g.features.filter(f => EAST.includes(f.properties.id)).map(f => rings(f).map(r => pd(r) + 'Z').join('')).join('');
fs.writeFileSync(out, '// Generated by gdr_build.js from isellsoap/deutschlandGeoJSON (2_bundeslaender/3_mittel), map image pixel space\r\nwindow.GDR = ' +
  JSON.stringify({ border: pd(line), east, pt: { berlin: P([13.4, 52.52]), su: P([11.75, 51.25]), east: P([13.0, 52.0]), west: P([9.0, 51.6]) } }) + ';\r\n');
